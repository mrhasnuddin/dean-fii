// SEO, AEO and GEO files, generated from the content so they never drift (docs/device-design.md §47):
//   public/llms.txt, public/llms-full.txt   a plain-text map of the site for AI assistants and answer engines
//   public/sitemap.xml                      the page and its share image, with today's date
//   index.html, between the seo markers     JSON-LD: the site, Dean, the studio and the list of works
// Runs before every build (npm run build) and by hand: node scripts/seo/generate.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SITE = 'https://www.dean-fi.my/';
const read = (p) => readFileSync(join(ROOT, p), 'utf8');
const data = JSON.parse(read('src/content/portfolio.json'));
const html = read('index.html');
const description = html.match(/<meta name="description" content="([^"]*)"/)[1];
const abs = (p) => new URL(p, SITE).href;

// Facts about Dean: no email, no phone, no full name (the site only ever says Dean).
const DEAN = {
  jobTitle: 'AI-native designer and frontend developer',
  description:
    'AI-native designer who also ships the frontend, with no handoff between design and build: UI/UX and creative design for user interfaces, landing pages and frontend builds that are easy to understand. Web3 and blockchain speaker, presenter and educator.',
  knowsAbout: ['AI-native design', 'UI/UX design', 'Frontend development', 'Creative design', 'Web3', 'Blockchain', 'Public speaking'],
  sameAs: ['https://www.linkedin.com/in/hasnuddin/'],
  services: ['UI/UX design', 'Frontend development', 'Creative design', 'Web3 product design'],
};
const works = [...data.projects.map((p) => ({ ...p, kind: 'Web' })), ...data.apps.map((p) => ({ ...p, kind: 'Mobile app' }))];

// ---------------------------------------------------------------- JSON-LD
const work = (p, i) => ({
  '@type': 'ListItem',
  position: i + 1,
  item: {
    '@type': 'CreativeWork',
    name: p.title,
    url: p.link,
    description: p.description,
    genre: p.category,
    keywords: [...p.stack, ...(p.chain ? [p.chain.name] : [])].join(', '),
    image: abs(p.images[0]),
    creator: { '@id': SITE + '#dean' },
    ...(p.original ? { isBasedOn: p.original.link } : {}),
  },
});
const graph = {
  '@context': 'https://schema.org',
  '@graph': [
    { '@type': 'WebSite', '@id': SITE + '#website', url: SITE, name: 'Dean Studio', description, inLanguage: 'en', publisher: { '@id': SITE + '#dean' } },
    {
      '@type': 'Person', '@id': SITE + '#dean', name: 'Dean', url: SITE, image: abs('media/dean-portrait.webp'),
      jobTitle: DEAN.jobTitle, description: DEAN.description, knowsAbout: DEAN.knowsAbout, sameAs: DEAN.sameAs, worksFor: { '@id': SITE + '#studio' },
    },
    {
      '@type': 'ProfessionalService', '@id': SITE + '#studio', name: 'Dean Studio', url: SITE, logo: abs('icon-512.png'), image: abs('og-image.jpg'),
      description, founder: { '@id': SITE + '#dean' }, serviceType: DEAN.services,
    },
    { '@type': 'ItemList', '@id': SITE + '#works', name: 'Selected works', numberOfItems: works.length, itemListElement: works.map(work) },
  ],
};
const block = `<!-- seo:start (generated by scripts/seo/generate.mjs: edit the content, not this) -->\n  <script type="application/ld+json">${JSON.stringify(graph)}</script>\n  <!-- seo:end -->`;
const marked = /<!-- seo:start[\s\S]*?<!-- seo:end -->/;
const legacy = /<script type="application\/ld\+json">[\s\S]*?<\/script>/;
const next = marked.test(html) ? html.replace(marked, block) : html.replace(legacy, block);
if (next !== html) writeFileSync(join(ROOT, 'index.html'), next);

// ---------------------------------------------------------------- llms.txt
const line = (p) => `- [${p.title}](${p.link}): ${p.category}. ${p.stack.join(', ')}.`;
const llms = `# Dean Studio

> ${description}

Dean Studio is the portfolio of Dean, an AI-native UI/UX designer and frontend developer. The site is an interactive 3D hardware-wallet-style device: its screen holds the works, events, about and contact; a plain List view shows the same content as a normal page. Site: ${SITE}

## Works (web)
${data.projects.map(line).join('\n')}

## Mobile apps
${data.apps.map((p) => `${line(p)} A redesign of ${p.original?.link ?? 'an existing app'}; runs on ${p.chain?.name ?? 'its own network'}.`).join('\n')}

## Events
${data.events.map((e) => `- ${e.title} (${e.place}, ${e.role}): ${e.description.split('. ')[0]}.`).join('\n')}

## More
- [Full detail of every work and event](${SITE}llms-full.txt)
- [LinkedIn](${DEAN.sameAs[0]})
- Contact: through the Get in touch section of ${SITE}
`;
writeFileSync(join(ROOT, 'public/llms.txt'), llms);

const full = `# Dean Studio, in full

> ${description}

Dean: ${DEAN.description}

Services: ${DEAN.services.join(', ')}.
Knows about: ${DEAN.knowsAbout.join(', ')}.
Profile: ${DEAN.sameAs[0]}
Site: ${SITE}

## Works

${works
  .map(
    (p) => `### ${p.title} (${p.kind})
- Category: ${p.category}
- Live: ${p.link}${p.original ? `\n- Redesigned from: ${p.original.link}` : ''}
- Roles: ${p.roles.join(', ')}
- Tools: ${p.tools.join(', ')}
- Tech stack: ${p.stack.join(', ')}${p.chain ? `\n- Network: ${p.chain.name}` : ''}
- Process: ${p.flow.steps.join(' > ')}
${p.description}
${p.flow.text}`,
  )
  .join('\n\n')}

## Events

${data.events
  .map((e) => `### ${e.title}\n- Where: ${e.place}\n- Role: ${e.role}${e.links ? `\n- Links: ${e.links.map((l) => `${l.title} ${l.link}`).join(', ')}` : ''}\n${e.description}`)
  .join('\n\n')}
`;
writeFileSync(join(ROOT, 'public/llms-full.txt'), full);

// ---------------------------------------------------------------- sitemap
const today = new Date().toISOString().slice(0, 10);
writeFileSync(
  join(ROOT, 'public/sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
  <url>
    <loc>${SITE}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>weekly</changefreq>
    <priority>1.0</priority>
    <image:image><image:loc>${abs('og-image.jpg')}</image:loc><image:title>Dean Studio</image:title></image:image>
  </url>
</urlset>
`,
);
console.log(`seo: ${works.length} works, ${data.events.length} events, JSON-LD ${JSON.stringify(graph).length} bytes, sitemap ${today}`);
